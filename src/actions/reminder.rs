use crate::tools::{ToolRegistry, ToolResult};
use serde_json::Value;
use std::path::PathBuf;

use super::{param, tool};

/// Built-in registered Windows PowerShell AUMID so Windows 10/11 actually shows Toast notifications.
#[cfg(windows)]
const POWERSHELL_AUMID: &str =
    r"{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}\WindowsPowerShell\v1.0\powershell.exe";

pub fn register(registry: &mut ToolRegistry) {
    registry.register(
        tool(
            "reminder",
            "Manage OS-scheduled reminders (Windows Task Scheduler) that fire even when Boogie is closed. \
             Actions: set (requires date YYYY-MM-DD, time HH:MM 24h, message), list (list active reminders), \
             cancel (requires name or keyword to cancel).",
            vec![
                ("action", param("action", "string", "set | list | cancel (default: set)")),
                ("date", param("date", "string", "Date in YYYY-MM-DD format (for set)")),
                ("time", param("time", "string", "Time in HH:MM 24-hour format (for set)")),
                ("message", param("message", "string", "Reminder message text (for set)")),
                ("name", param("name", "string", "Task name or keyword to cancel (for cancel)")),
            ],
            vec![],
        ),
        Box::new(|args| Box::pin(reminder(args))),
    );
}

fn scripts_dir() -> PathBuf {
    let dir = dirs::home_dir()
        .unwrap_or_else(|| PathBuf::from("."))
        .join(".boogie")
        .join("reminders");
    std::fs::create_dir_all(&dir).ok();
    dir
}

pub fn sanitize_message(text: &str) -> String {
    text.replace('\n', " ")
        .replace('\r', "")
        .trim()
        .chars()
        .take(200)
        .collect()
}

pub fn xml_escape(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

pub fn build_toast_ps1(message: &str) -> Vec<u8> {
    let safe_plain = sanitize_message(message);
    let safe_xml = xml_escape(&safe_plain);
    let ps_plain_escaped = safe_plain.replace('\'', "''");
    #[cfg(windows)]
    let aumid = POWERSHELL_AUMID;
    #[cfg(not(windows))]
    let aumid = r"{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}\WindowsPowerShell\v1.0\powershell.exe";

    let script = format!(
        r#"# Auto-generated by Boogie reminder
$plainMessage = '{ps_plain_escaped}'
$xmlMessage = @'
{safe_xml}
'@
try {{
    [Windows.UI.Notifications.ToastNotificationManager, Windows.UI.Notifications, ContentType = WindowsRuntime] | Out-Null
    [Windows.Data.Xml.Dom.XmlDocument, Windows.Data.Xml.Dom, ContentType = WindowsRuntime] | Out-Null
    $xml = @"
<toast>
  <visual>
    <binding template="ToastGeneric">
      <text>Boogie Reminder</text>
      <text>$xmlMessage</text>
    </binding>
  </visual>
  <audio src="ms-winsoundevent:Notification.Reminder"/>
</toast>
"@
    $doc = [Windows.Data.Xml.Dom.XmlDocument]::new()
    $doc.LoadXml($xml)
    $notifier = [Windows.UI.Notifications.ToastNotificationManager]::CreateToastNotifier("{aumid}")
    $toast = [Windows.UI.Notifications.ToastNotification]::new($doc)
    $notifier.Show($toast)
}} catch {{
    Add-Type -AssemblyName System.Windows.Forms
    [System.Windows.Forms.MessageBox]::Show($plainMessage, "Boogie Reminder") | Out-Null
}}
Remove-Item -Path $MyInvocation.MyCommand.Source -Force -ErrorAction SilentlyContinue
"#
    );

    // Prepend UTF-8 BOM (EF BB BF) so Windows PowerShell 5.1 reads Vietnamese UTF-8 properly
    let mut bytes = Vec::with_capacity(3 + script.len());
    bytes.extend_from_slice(&[0xEF, 0xBB, 0xBF]);
    bytes.extend_from_slice(script.as_bytes());
    bytes
}

async fn reminder(args: Value) -> ToolResult {
    let action = args
        .get("action")
        .and_then(|v| v.as_str())
        .unwrap_or("set")
        .trim()
        .to_lowercase();

    match action.as_str() {
        "list" => tokio::task::spawn_blocking(list_reminders_sync)
            .await
            .unwrap_or_else(|e| ToolResult::err(format!("list reminders failed: {e}"))),

        "cancel" | "delete" | "remove" => {
            let name = args
                .get("name")
                .or_else(|| args.get("message"))
                .and_then(|v| v.as_str())
                .unwrap_or_default()
                .trim()
                .to_string();
            if name.is_empty() {
                return ToolResult::err("Specify 'name' of the reminder to cancel.");
            }
            tokio::task::spawn_blocking(move || cancel_reminder_sync(&name))
                .await
                .unwrap_or_else(|e| ToolResult::err(format!("cancel reminder failed: {e}")))
        }

        _ => {
            let date_str = args
                .get("date")
                .and_then(|v| v.as_str())
                .unwrap_or_default()
                .trim()
                .to_string();
            let time_str = args
                .get("time")
                .and_then(|v| v.as_str())
                .unwrap_or_default()
                .trim()
                .to_string();
            let message = args
                .get("message")
                .and_then(|v| v.as_str())
                .unwrap_or("Reminder")
                .trim()
                .to_string();

            if date_str.is_empty() || time_str.is_empty() {
                return ToolResult::err("Need both date (YYYY-MM-DD) and time (HH:MM).");
            }

            let dt_str = format!("{date_str} {time_str}");
            let target = match chrono::NaiveDateTime::parse_from_str(&dt_str, "%Y-%m-%d %H:%M") {
                Ok(dt) => dt,
                Err(_) => {
                    return ToolResult::err(
                        "Could not parse date/time. Use YYYY-MM-DD and HH:MM (24h).",
                    );
                }
            };

            let now = chrono::Local::now().naive_local();
            if target <= now {
                return ToolResult::err("That time has already passed.");
            }

            let task_name = format!("BoogieReminder_{}", target.format("%Y%m%d_%H%M%S"));

            #[cfg(windows)]
            {
                tokio::task::spawn_blocking(move || {
                    match schedule_windows(&target, &task_name, &message) {
                        Ok(()) => {
                            let friendly = target.format("%Y-%m-%d %H:%M").to_string();
                            ToolResult::ok(format!("Reminder '{task_name}' set for {friendly}."))
                        }
                        Err(e) => ToolResult::err(format!("Failed to schedule reminder: {e}")),
                    }
                })
                .await
                .unwrap_or_else(|e| ToolResult::err(format!("reminder task failed: {e}")))
            }

            #[cfg(not(windows))]
            {
                let _ = (target, task_name, message);
                ToolResult::err("Reminders are currently Windows-only")
            }
        }
    }
}

fn list_reminders_sync() -> ToolResult {
    let dir = scripts_dir();
    let mut items = Vec::new();
    if let Ok(entries) = std::fs::read_dir(&dir) {
        for entry in entries.flatten() {
            let fname = entry.file_name().to_string_lossy().to_string();
            if let Some(task) = fname.strip_suffix(".ps1") {
                items.push(task.to_string());
            }
        }
    }
    items.sort();
    if items.is_empty() {
        ToolResult::ok("No pending reminders.")
    } else {
        ToolResult::ok(format!("Active reminders:\n{}", items.join("\n")))
    }
}

fn cancel_reminder_sync(query: &str) -> ToolResult {
    let dir = scripts_dir();
    let lower = query.to_lowercase();
    let mut matched = None;
    if let Ok(entries) = std::fs::read_dir(&dir) {
        for entry in entries.flatten() {
            let fname = entry.file_name().to_string_lossy().to_string();
            if let Some(task) = fname.strip_suffix(".ps1")
                && task.to_lowercase().contains(&lower)
            {
                matched = Some((task.to_string(), entry.path()));
                break;
            }
        }
    }

    let Some((task_name, script_path)) = matched else {
        return ToolResult::err(format!("No reminder found matching '{query}'."));
    };

    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        let _ = std::process::Command::new("schtasks")
            .args(["/Delete", "/TN", &task_name, "/F"])
            .creation_flags(0x08000000)
            .output();
    }
    let _ = std::fs::remove_file(&script_path);
    ToolResult::ok(format!("Cancelled reminder '{task_name}'."))
}

#[cfg(windows)]
fn schedule_windows(
    target: &chrono::NaiveDateTime,
    task_name: &str,
    message: &str,
) -> Result<(), String> {
    use std::os::windows::process::CommandExt;

    let script_path = scripts_dir().join(format!("{task_name}.ps1"));
    let ps_bytes = build_toast_ps1(message);
    std::fs::write(&script_path, &ps_bytes).map_err(|e| format!("write script: {e}"))?;

    let xml_path = scripts_dir().join(format!("{task_name}.xml"));
    let start_boundary = target.format("%Y-%m-%dT%H:%M:%S").to_string();
    let script_xml_escaped = xml_escape(&script_path.to_string_lossy());
    let xml_content = format!(
        r#"<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo><Description>Boogie Reminder</Description></RegistrationInfo>
  <Triggers><TimeTrigger>
    <StartBoundary>{start_boundary}</StartBoundary>
    <Enabled>true</Enabled>
  </TimeTrigger></Triggers>
  <Actions><Exec>
    <Command>powershell</Command>
    <Arguments>-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File "{script_xml_escaped}"</Arguments>
  </Exec></Actions>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <StartWhenAvailable>true</StartWhenAvailable>
    <ExecutionTimeLimit>PT5M</ExecutionTimeLimit>
    <Enabled>true</Enabled>
  </Settings>
  <Principals><Principal>
    <LogonType>InteractiveToken</LogonType>
    <RunLevel>LeastPrivilege</RunLevel>
  </Principal></Principals>
</Task>"#
    );

    let xml_bytes: Vec<u8> = {
        let mut v = vec![0xFF, 0xFE]; // UTF-16 LE BOM
        for ch in xml_content.encode_utf16() {
            v.extend_from_slice(&ch.to_le_bytes());
        }
        v
    };
    std::fs::write(&xml_path, &xml_bytes).map_err(|e| format!("write xml: {e}"))?;

    let result = std::process::Command::new("schtasks")
        .args([
            "/Create",
            "/TN",
            task_name,
            "/XML",
            &xml_path.to_string_lossy(),
            "/F",
        ])
        .creation_flags(0x08000000)
        .output()
        .map_err(|e| format!("schtasks: {e}"))?;

    let _ = std::fs::remove_file(&xml_path);

    if !result.status.success() {
        let _ = std::fs::remove_file(&script_path);
        let err = String::from_utf8_lossy(&result.stderr);
        let out = String::from_utf8_lossy(&result.stdout);
        return Err(format!("schtasks failed: {}{}", err.trim(), out.trim()));
    }

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn toast_script_has_utf8_bom_and_escapes_xml_special_chars() {
        let bytes = build_toast_ps1("Uống thuốc & kiểm tra <email>");
        assert_eq!(&bytes[..3], &[0xEF, 0xBB, 0xBF]);
        let text = std::str::from_utf8(&bytes[3..]).unwrap();
        assert!(text.contains("Uống thuốc &amp; kiểm tra &lt;email&gt;"));
        assert!(text.contains("WindowsPowerShell\\v1.0\\powershell.exe"));
    }
}
